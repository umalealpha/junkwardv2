<script>
    "use strict";
    // Class definition
    var KTFormControls = function () {
        var demo1 = function () {
            $( "#cancelCronForm" ).validate({
                rules: {
                    cron_name: {
                        required: true,
                        minlength: 2
                    }
                },
                messages: {
                    cron_name: {
                        required: "Please enter a cron command name",
                        minlength: "Cron command name must be at least 2 characters"
                    }
                },
                //display error alert on form submit
                invalidHandler: function(event, validator) {
                    KTUtil.scrollTo("cancelCronForm", -200);
                    $('#btn').show();
                },
                submitHandler: function (form) {
                    if(confirm('Are you sure you want to cancel/deactivate this cron job? This action will stop the cron from running.')) {
                        $('#btn').hide();
                        $('#loadBtn').show();
                        form[0].submit(); // submit the form
                    }
                }
            });
        }

        return {
            // public functions
            init: function() {
                demo1();
            }
        };
    }();

    jQuery(document).ready(function() {
        KTFormControls.init();
    });
</script>

